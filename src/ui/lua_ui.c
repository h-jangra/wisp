static int preload_upvalue(lua_State *L)
{
	lua_pushvalue(L, lua_upvalueindex(1));
	return 1;
}

static void register_preload(lua_State *L, const char *name, int table_idx)
{
	lua_getglobal(L, "package");
	if (!lua_istable(L, -1)) {
		lua_pop(L, 1);
		return;
	}
	lua_getfield(L, -1, "preload");
	if (!lua_istable(L, -1)) {
		lua_pop(L, 2);
		return;
	}
	lua_pushvalue(L, table_idx);
	lua_pushcclosure(L, preload_upvalue, 1);
	lua_setfield(L, -2, name);
	lua_pop(L, 2);
}

void ui_register_lua(lua_State *L)
{
	if (luaL_dostring(L, wisp_ui_lua) != LUA_OK) {
		fprintf(stderr, "wisp: failed to load wisp.ui: %s\n", lua_tostring(L, -1));
		lua_pop(L, 1);
		return;
	}

	lua_getglobal(L, "gears");
	if (lua_istable(L, -1)) {
		register_preload(L, "gears", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getglobal(L, "wibox");
	if (lua_istable(L, -1)) {
		register_preload(L, "wibox", lua_gettop(L));
		lua_getfield(L, -1, "widget");
		if (lua_istable(L, -1)) {
			register_preload(L, "wibox.widget", lua_gettop(L));
		}
		lua_pop(L, 1);
	}
	lua_pop(L, 1);

	lua_getglobal(L, "awful");
	if (lua_istable(L, -1)) {
		register_preload(L, "awful", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getglobal(L, "wisp");
	if (!lua_istable(L, -1)) {
		lua_pop(L, 1);
		return;
	}

	int wisp_idx = lua_gettop(L);

	lua_getfield(L, wisp_idx, "ui");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.ui", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "object");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.object", lua_gettop(L));
		register_preload(L, "gears.object", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "widget");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.widget", lua_gettop(L));
		lua_getfield(L, -1, "base");
		if (lua_istable(L, -1)) {
			register_preload(L, "wisp.widget.base", lua_gettop(L));
			register_preload(L, "wibox.widget.base", lua_gettop(L));
		}
		lua_pop(L, 1);
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "layout");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.layout", lua_gettop(L));
		register_preload(L, "wibox.layout", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "container");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.container", lua_gettop(L));
		register_preload(L, "wibox.container", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "popup");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.popup", lua_gettop(L));
		register_preload(L, "awful.popup", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_getfield(L, wisp_idx, "tooltip");
	if (lua_istable(L, -1)) {
		register_preload(L, "wisp.tooltip", lua_gettop(L));
		register_preload(L, "awful.tooltip", lua_gettop(L));
	}
	lua_pop(L, 1);

	lua_pop(L, 1); /* pop wisp */
}
